#!/usr/bin/env python3
"""Crop the bongo cat frames to the peripheral panel and emit them as LVGL I1 images.

Source:  <repo>/art/bongo_source.c   - the supplied 128x40 frames, verbatim
Output:  boards/shields/keeb/ui/art/bongo_art.c   (data + frame tables)
         boards/shields/keeb/ui/art/bongo_art.h   (counts + declarations)

Why crop instead of scale: the panel composes in a 68 px wide portrait space
(CONFIG_KEEB_UI_ROTATION_90) and LVGL's software renderer in this build has no
image transform, so the frames are cropped to the panel width - centred on the
ink, with the cat on top of the panel and the readouts below it.

Why A8 and not the supplied 1-bit indexed: LVGL's decoder expands an indexed
image to a full-colour buffer before drawing it, and this build's LVGL heap is
8 KB - a 68x40 ARGB8888 frame is 10.8 KB, so it would fail to allocate. A8 is
what the layer artwork already uses: one byte of alpha per pixel, recoloured to
the panel's ink at draw time, 2720 bytes per frame.

Run after replacing art/bongo_source.c:

    python3 tools/gen_bongo.py
"""

import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "art", "bongo_source.c")
OUT_DIR = os.path.join(REPO, "boards", "shields", "keeb", "ui", "art")

WIDTH = 128  # source frame width
HEIGHT = 40
CROP_W = 68  # the peripheral panel's logical width in portrait
PALETTE_BYTES = 8

# fast typing, slow typing, idle. Order matters: the panel indexes these.
GROUPS = [
    ("fast", ["fast1", "fast2"]),
    ("slow", ["slow"]),
    ("idle", ["idle1", "idle2", "idle3", "idle4", "idle5"]),
]


def load_frames():
    text = open(SRC).read()
    palette = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})",
                                                   re.search(r"#define BONGO_PALETTE (.*)", text).group(1)))
    assert len(palette) == PALETTE_BYTES

    frames = {}
    for name, body in re.findall(r"static const uint8_t bongo_(\w+)_map\[\] __aligned\(4\) = \{(.*?)\n\};",
                                 text, re.S):
        data = palette + bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body))
        if len(data) != PALETTE_BYTES + WIDTH * HEIGHT // 8:
            raise SystemExit(f"{name}: {len(data)} bytes, expected {PALETTE_BYTES + WIDTH * HEIGHT // 8}")
        frames[name] = data
    return palette, frames


def ink_columns(frames):
    counts = [0] * WIDTH
    for data in frames.values():
        bitmap = data[PALETTE_BYTES:]
        for y in range(HEIGHT):
            row = bitmap[y * WIDTH // 8:(y + 1) * WIDTH // 8]
            for x in range(WIDTH):
                if (row[x // 8] >> (7 - (x % 8))) & 1:
                    counts[x] += 1
    return counts


def crop_window(frames):
    """Centre the 68 px window on the frames' dense columns, clamped to the frame.

    Dense = more ink than the thin diagonal that runs through every frame edge to
    edge, which would otherwise drag the window off the cat."""
    counts = ink_columns(frames)
    floor = min(c for c in counts if c) if any(counts) else 0
    dense = [x for x, c in enumerate(counts) if c > floor]
    centre = ((dense[0] + dense[-1]) // 2) if dense else WIDTH // 2
    return min(max(0, centre - CROP_W // 2), WIDTH - CROP_W)


A8_STRIDE = (CROP_W + 3) & ~3


def crop(data, start):
    """The 68 columns [start, start+68) as an A8 mask: 255 where the source set a
    bit (the drawing), 0 elsewhere (paper)."""
    bitmap = data[PALETTE_BYTES:]
    out = bytearray(A8_STRIDE * HEIGHT)
    for y in range(HEIGHT):
        for x in range(CROP_W):
            src = bitmap[y * WIDTH // 8 + (start + x) // 8]
            if (src >> (7 - ((start + x) % 8))) & 1:
                out[y * A8_STRIDE + x] = 255
    return bytes(out)


def c_array(data, per_line=17):
    return "\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ","
                     for i in range(0, len(data), per_line))


def main():
    _, frames = load_frames()
    start = crop_window(frames)
    stride = A8_STRIDE

    out = open(os.path.join(OUT_DIR, "bongo_art.c"), "w")
    out.write("/* GENERATED by tools/gen_bongo.py - do not edit.\n"
              " * Bongo cat frames from art/bongo_source.c, cropped to the panel width\n"
              f" * (columns {start}..{start + CROP_W - 1} of {WIDTH}x{HEIGHT}, {CROP_W}x{HEIGHT}).\n"
              " */\n\n"
              "#include <lvgl.h>\n"
              "#include <zephyr/toolchain.h>\n\n"
              '#include "bongo_art.h"\n\n')

    for suffix, names in GROUPS:
        for name in names:
            data = crop(frames[name], start)
            out.write(f"static const uint8_t bongo_{name}_map[] __aligned(4) = {{\n{c_array(data)}\n}};\n\n")
            out.write(f"static const lv_image_dsc_t bongo_{name} = {{\n"
                      "    .header = {\n"
                      f"        .cf = LV_COLOR_FORMAT_A8,\n"
                      f"        .w = {CROP_W},\n"
                      f"        .h = {HEIGHT},\n"
                      f"        .stride = {stride},\n"
                      "    },\n"
                      f"    .data_size = sizeof(bongo_{name}_map),\n"
                      f"    .data = bongo_{name}_map,\n"
                      "};\n\n")

        out.write(f"const lv_image_dsc_t *const keeb_bongo_{suffix}[BONGO_{suffix.upper()}_COUNT] = {{\n")
        out.write("".join(f"    &bongo_{n},\n" for n in names))
        out.write("};\n\n")

    out.close()

    head = open(os.path.join(OUT_DIR, "bongo_art.h"), "w")
    head.write("/* GENERATED by tools/gen_bongo.py - do not edit. */\n"
               "#pragma once\n\n"
               "#include <lvgl.h>\n\n"
               f"/** Frames per mood, cropped to {CROP_W}x{HEIGHT} for the panel. */\n")
    for suffix, names in GROUPS:
        head.write(f"#define BONGO_{suffix.upper()}_COUNT {len(names)}\n")
    head.write("\n")
    for suffix, _ in GROUPS:
        head.write(f"extern const lv_image_dsc_t *const keeb_bongo_{suffix}[BONGO_{suffix.upper()}_COUNT];\n")
    head.close()

    print(f"bongo_art.c: {sum(len(n) for _, n in GROUPS)} frames, crop {start}..{start + CROP_W - 1}")


main()
